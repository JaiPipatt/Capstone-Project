#!/usr/bin/env python3
"""Compute mass, center of mass and inertia tensor of each URDF link from its mesh.

Assumes a solid part of uniform density. Each link uses meshes/<link>_visual.obj,
placed by the link's <visual><origin>, so results are in the link frame.
The output is urdf/inertial.xacro, one <xacro:LINK_inertial/> macro per link.

Usage:
  compute_inertia.py                          # print results (nylon PA12, solid)
  compute_inertia.py --density 1140           # e.g. nylon PA6
  compute_inertia.py --mass base_link=0.215   # use a weighed mass for a link
  compute_inertia.py --write                  # regenerate urdf/inertial.xacro
"""
import argparse
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np
import xacro

PKG = Path(__file__).resolve().parent.parent
NYLON_PA12 = 1010.0  # kg/m^3


def load_obj(path):
    verts, faces = [], []
    for line in open(path):
        if line.startswith('v '):
            verts.append([float(x) for x in line.split()[1:4]])
        elif line.startswith('f '):
            idx = [int(t.split('/')[0]) for t in line.split()[1:]]
            idx = [i - 1 if i > 0 else len(verts) + i for i in idx]
            faces += [[idx[0], idx[k], idx[k + 1]] for k in range(1, len(idx) - 1)]
    return np.array(verts), np.array(faces)


def mass_properties(verts, faces):
    """Volume, COM and inertia per unit density of a closed mesh (signed tetrahedra)."""
    a, b, c = verts[faces[:, 0]], verts[faces[:, 1]], verts[faces[:, 2]]
    vol = np.einsum('ij,ij->i', a, np.cross(b, c)) / 6.0
    volume = vol.sum()
    com = ((a + b + c) / 4 * vol[:, None]).sum(0) / volume
    s = a + b + c
    cov = sum(np.einsum('i,ij,ik->jk', vol, v, v) for v in (a, b, c, s)) / 20.0
    cov -= volume * np.outer(com, com)
    inertia = np.trace(cov) * np.eye(3) - cov
    return abs(volume), com, inertia * np.sign(volume)


def rpy_matrix(r, p, y):
    cr, sr, cp, sp, cy, sy = np.cos(r), np.sin(r), np.cos(p), np.sin(p), np.cos(y), np.sin(y)
    rz = np.array([[cy, -sy, 0], [sy, cy, 0], [0, 0, 1]])
    ry = np.array([[cp, 0, sp], [0, 1, 0], [-sp, 0, cp]])
    rx = np.array([[1, 0, 0], [0, cr, -sr], [0, sr, cr]])
    return rz @ ry @ rx


def inertial_xml(mass, com, inertia, indent):
    i = inertia
    return (
        f'{indent}<inertial>\n'
        f'{indent}  <origin xyz="{com[0]:.6f} {com[1]:.6f} {com[2]:.6f}" rpy="0 0 0" />\n'
        f'{indent}  <mass value="{mass:.6f}" />\n'
        f'{indent}  <inertia ixx="{i[0, 0]:.4e}" ixy="{i[0, 1]:.4e}" ixz="{i[0, 2]:.4e}" '
        f'iyy="{i[1, 1]:.4e}" iyz="{i[1, 2]:.4e}" izz="{i[2, 2]:.4e}" />\n'
        f'{indent}</inertial>'
    ).replace('-0.000000', '0.000000')


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--xacro', type=Path, default=PKG / 'urdf' / 'my_robot.urdf.xacro')
    parser.add_argument('--out', type=Path, default=PKG / 'urdf' / 'inertial.xacro')
    parser.add_argument('--density', type=float, default=NYLON_PA12, help='kg/m^3 (default: nylon PA12)')
    parser.add_argument('--mass', action='append', default=[], metavar='LINK=KG',
                        help='override mass of a link with a measured value')
    parser.add_argument('--write', action='store_true', help='regenerate the inertial xacro file')
    args = parser.parse_args()
    overrides = {k: float(v) for k, v in (m.split('=') for m in args.mass)}

    # Expand the full robot to read each link's mesh placement.
    robot = ET.fromstring(xacro.process_file(str(args.xacro)).toxml())

    macros = []
    for link in robot.findall('link'):
        name = link.get('name')
        origin = link.find('visual/origin')
        rot = rpy_matrix(*map(float, origin.get('rpy', '0 0 0').split()))
        offset = np.array([float(x) for x in origin.get('xyz', '0 0 0').split()])

        volume, com, inertia = mass_properties(*load_obj(PKG / 'meshes' / f'{name}_visual.obj'))
        mass = overrides.get(name, args.density * volume)
        com = rot @ com + offset
        inertia = rot @ (inertia * mass / volume) @ rot.T

        source = 'measured' if name in overrides else f'{args.density:g} kg/m^3, solid'
        print(f'{name}: volume={volume * 1e6:.2f} cm^3  mass={mass * 1000:.1f} g  ({source})')
        macros.append(
            f'  <!-- {name}: {volume * 1e6:.2f} cm^3, mass {source} -->\n'
            f'  <xacro:macro name="{name}_inertial">\n'
            f'{inertial_xml(mass, com, inertia, "    ")}\n'
            f'  </xacro:macro>\n')

    text = (
        '<?xml version="1.0"?>\n'
        '<!-- GENERATED by scripts/compute_inertia.py from the meshes. Do not edit by hand. -->\n'
        '<robot xmlns:xacro="http://www.ros.org/wiki/xacro">\n\n'
        + '\n'.join(macros) + '\n</robot>\n')
    if args.write:
        args.out.write_text(text)
        print(f'wrote {args.out}')
    else:
        print(text)


if __name__ == '__main__':
    main()
